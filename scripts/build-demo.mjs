// Generates src/demo/demoHtml.ts from the bridge's public/index.html.
// The demo build is the same page with `window.__TETHERDECK_DEMO__ = true`
// set before the main script runs; the page then serves bundled sample data
// instead of calling /api/*. App Review can use the app with no server.
//
// Usage: node scripts/build-demo.mjs [path-to-index.html]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] || resolve(here, '../../phone-claude-bridge/public/index.html'));
const out = resolve(here, '../src/demo/demoHtml.ts');

let html = readFileSync(src, 'utf8');
const anchor = "<script>\n'use strict';";
if (!html.includes(anchor)) {
  console.error('anchor not found in ' + src + ' — page structure changed, update build-demo.mjs');
  process.exit(1);
}
html = html.replace(
  anchor,
  '<script>window.__TETHERDECK_DEMO__ = true;</script>\n' + anchor
);

// JSON.stringify yields a valid JS string literal; escape line separators for safety.
const LS = String.fromCharCode(0x2028);
const PS = String.fromCharCode(0x2029);
const literal = JSON.stringify(html)
  .split(LS).join('\\u2028')
  .split(PS).join('\\u2029');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/build-demo.mjs — do not edit.\n' +
    '// Source: ' + src.replace(/\\/g, '/') + '\n' +
    'export const DEMO_HTML: string = ' + literal + ';\n',
  'utf8'
);
console.log('wrote ' + out + ' (' + html.length + ' chars)');
